    v = wb[VID]; z = f"{SL0}{P}:{SL1}{RYADKY}"
    v.conditional_formatting.add(z, CellIsRule(operator="equal", formula=['"+"'], fill=zel))
    v.conditional_formatting.add(z, CellIsRule(operator="equal", formula=['"−"'], fill=roz))
    v.conditional_formatting.add(z, CellIsRule(operator="equal", formula=['"в"'], fill=bur))
    for i in range(S0, S1 + 1):
        c = v.cell(H, i); c.fill = fill(GOLD); c.font = FH
